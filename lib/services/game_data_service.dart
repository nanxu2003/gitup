  // 默认建筑
  static List<Building> getDefaultBuildings() {
    return BuildingType.values.map((type) {
      return Building(
        type: type,
        name: buildingNames[type] ?? '',
        level: type == BuildingType.government ? 1 : 0,
        maxLevel: 10,
        upgradeCost: _buildingUpgradeCost(type),
        upgradeTimeSeconds: 120,
      );
    }).toList();
  }

  static Map<String, int> _buildingUpgradeCost(BuildingType type) {
    switch (type) {
      case BuildingType.government:
        return {'coin': 1000, 'wood': 500};
      case BuildingType.farm:
        return {'coin': 500, 'wood': 200};
      case BuildingType.market:
        return {'coin': 600, 'wood': 300};
      case BuildingType.lumberMill:
        return {'coin': 400, 'wood': 100};
      case BuildingType.ironWorks:
        return {'coin': 500, 'iron': 100};
      case BuildingType.barracks:
        return {'coin': 800, 'wood': 400};
      case BuildingType.trainingGround:
        return {'coin': 700, 'wood': 300};
      case BuildingType.tavern:
        return {'coin': 600, 'wood': 250};
      case BuildingType.blacksmith:
        return {'coin': 500, 'iron': 200};
      case BuildingType.academy:
        return {'coin': 800, 'wood': 300};
      case BuildingType.postStation:
        return {'coin': 400, 'wood': 200};
      case BuildingType.wall:
        return {'coin': 600, 'wood': 400, 'iron': 200};
    }
  }

