  static Skill? findSkill(String skillId) {
    final skills = getAllSkills();
    for (final s in skills) {
      if (s.id == skillId) return s;
    }
    return null;
  }

  // 根据ID查找敌人
  static Enemy? findEnemy(String enemyId) {
    final enemies = getAllEnemies();
    for (final e in enemies) {
      if (e.id == enemyId) return e;
    }
    return null;
  }
